#!/usr/bin/env python3
"""The Homebrew formulas and the Scoop manifest of a muster release, generated
from the release's own checksums.txt — so every URL names an asset of THIS
release and every hash is the one its checksums.txt verifies.

    scripts/release-manifests.py --version 1.2.3 --repo ZacxDev/muster \\
        --checksums dist/checksums.txt --out dist

writes, into --out:
    muster.rb          Homebrew formula: the muster CLI (macOS, Linux; amd64, arm64)
    muster-mirror.rb   Homebrew formula: muster-mirror, depends on tmux
    muster.json        Scoop manifest: the muster CLI on Windows (amd64, arm64)

scripts/release-build.sh runs it and attaches the three files to the release.
They are NOT published to a tap or bucket by anything here: a tap repository
(`<owner>/homebrew-muster`) and a Scoop bucket are the operator's decision
(docs/releases.md, "Homebrew and Scoop"). There is no Scoop manifest for
muster-mirror: it needs tmux, which Windows does not have.

Deterministic: the output is a pure function of the arguments and the
checksums file (tests/release_manifests_test.py pins it).
Exit 0 ok; 2 usage, or an asset the manifests need is not in checksums.txt.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")

# Homebrew's (os, cpu) blocks -> the release's asset suffix.
BREW_PLATFORMS = [
    ("on_macos", "on_arm", "darwin_arm64"),
    ("on_macos", "on_intel", "darwin_amd64"),
    ("on_linux", "on_arm", "linux_arm64"),
    ("on_linux", "on_intel", "linux_amd64"),
]
# Scoop's architecture keys -> the release's asset suffix.
SCOOP_ARCHES = [("64bit", "windows_amd64"), ("arm64", "windows_arm64")]

FORMULAS = {
    "muster": {
        "class": "Muster",
        "desc": "Command-line client for a muster server",
        "depends": [],
        "test": '"#{bin}/muster --version"',
        "caveats": None,
    },
    "muster-mirror": {
        "class": "MusterMirror",
        "desc": "Shows this machine's tmux sessions in muster",
        "depends": ["tmux"],
        "test": '"#{bin}/muster-mirror -version"',
        "caveats": (
            "muster-mirror needs its settings (~/.config/muster-mirror/env) and a\n"
            "      mirror token before it can connect: run the release's install.sh, or\n"
            "      see docs/mirroring.md in the muster repository."
        ),
    },
}


class Unusable(Exception):
    pass


def read_checksums(path: str) -> dict[str, str]:
    sums: dict[str, str] = {}
    try:
        with open(path, encoding="utf-8") as f:
            for n, raw in enumerate(f, 1):
                parts = raw.split()
                if not parts:
                    continue
                if len(parts) != 2 or not re.fullmatch(r"[0-9a-f]{64}", parts[0]):
                    raise Unusable(f"{path}:{n}: not a sha256sum line: {raw.rstrip()!r}")
                sums[parts[1].lstrip("*")] = parts[0]
    except OSError as e:
        raise Unusable(f"cannot read {path}: {e}") from e
    return sums


def need(sums: dict[str, str], asset: str) -> str:
    if asset not in sums:
        raise Unusable(f"{asset} is not in checksums.txt; the manifests cannot name it")
    return sums[asset]


def formula(name: str, version: str, repo: str, sums: dict[str, str]) -> str:
    spec = FORMULAS[name]
    base = f"https://github.com/{repo}/releases/download/v{version}"
    out = [
        f"# Generated by scripts/release-manifests.py for muster {version}; do not edit.",
        f"class {spec['class']} < Formula",
        f'  desc "{spec["desc"]}"',
        f'  homepage "https://github.com/{repo}"',
        f'  version "{version}"',
        '  license "MIT"',
    ]
    for dep in spec["depends"]:
        out.append(f'  depends_on "{dep}"')
    for os_block in ("on_macos", "on_linux"):
        out += ["", f"  {os_block} do"]
        for ob, cpu, suffix in BREW_PLATFORMS:
            if ob != os_block:
                continue
            asset = f"{name}_{suffix}.tar.gz"
            out += [
                f"    {cpu} do",
                f'      url "{base}/{asset}"',
                f'      sha256 "{need(sums, asset)}"',
                "    end",
            ]
        out.append("  end")
    out += ["", "  def install", f'    bin.install "{name}"', "  end"]
    if spec["caveats"]:
        out += ["", "  def caveats", "    <<~EOS", f"      {spec['caveats']}", "    EOS", "  end"]
    out += [
        "",
        "  test do",
        f"    assert_match version.to_s, shell_output({spec['test']})",
        "  end",
        "end",
    ]
    return "\n".join(out) + "\n"


def scoop(version: str, repo: str, sums: dict[str, str]) -> str:
    base = f"https://github.com/{repo}/releases/download/v{version}"
    arch = {}
    auto = {}
    for key, suffix in SCOOP_ARCHES:
        asset = f"muster_{suffix}.zip"
        arch[key] = {"url": f"{base}/{asset}", "hash": need(sums, asset)}
        auto[key] = {"url": f"https://github.com/{repo}/releases/download/v$version/{asset}"}
    manifest = {
        "version": version,
        "description": "Command-line client for a muster server (muster-mirror needs tmux and is not available on Windows)",
        "homepage": f"https://github.com/{repo}",
        "license": "MIT",
        "architecture": arch,
        "bin": "muster.exe",
        "checkver": "github",
        "autoupdate": {
            "architecture": auto,
            "hash": {"url": "$baseurl/checksums.txt"},
        },
    }
    return json.dumps(manifest, indent=2) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--version", required=True)
    ap.add_argument("--repo", required=True)
    ap.add_argument("--checksums", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    try:
        v = a.version[1:] if a.version.startswith("v") else a.version
        if not VERSION_RE.match(v):
            raise Unusable(f"version {a.version!r} is not X.Y.Z")
        if not REPO_RE.match(a.repo):
            raise Unusable(f"repo {a.repo!r} is not owner/name")
        sums = read_checksums(a.checksums)
        files = {
            "muster.rb": formula("muster", v, a.repo, sums),
            "muster-mirror.rb": formula("muster-mirror", v, a.repo, sums),
            "muster.json": scoop(v, a.repo, sums),
        }
    except Unusable as e:
        print(f"release-manifests: {e}", file=sys.stderr)
        return 2
    for name, text in files.items():
        with open(os.path.join(a.out, name), "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
