#!/usr/bin/env python3
"""Print tests/leakscan_denylist.txt from plaintext names and the HMAC key.

    MUSTER_LEAKSCAN_KEY=… python3 scripts/leakscan-rehash.py < names.txt \\
        > tests/leakscan_denylist.txt

Reads one name per line on stdin (blank lines and `#` lines are ignored) and
the key from MUSTER_LEAKSCAN_KEY. Keep the names file OUTSIDE this repository:
the point of the digests is that the names are never committed.

It never prints a name or the key. A name it cannot use is reported by its
line number only.

Exit codes: 0 written, 2 refused (no key, a bad name, or no names at all).
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tests"))
import leakscan  # noqa: E402

HEADER = """\
# HMAC-SHA256 digests of tests/leakscan.py's denied identifiers, keyed with
# MUSTER_LEAKSCAN_KEY. Generated by scripts/leakscan-rehash.py; do not edit by
# hand. One digest per line; `#` lines are comments.
"""


def rehash(lines: list[str], key: bytes) -> list[str]:
    """The sorted digests of `lines`. Raises DenylistError on a bad name."""
    names: list[str] = []
    for n, raw in enumerate(lines, start=1):
        if not raw.strip() or raw.strip().startswith("#"):
            continue
        name = leakscan.normalise_name(raw)
        problem = leakscan.name_problem(name)
        if problem:
            raise leakscan.DenylistError(f"stdin line {n}: {problem}")
        if name not in names:
            names.append(name)
    if not names:
        raise leakscan.DenylistError("no names on stdin")
    deny = leakscan.Denylist(key, [])
    return sorted(deny.digest(name) for name in names)


def main() -> int:
    try:
        key = leakscan.leakscan_key()
        if key is None:
            raise leakscan.DenylistError(f"{leakscan.LEAKSCAN_KEY_ENV} is not set")
        digests = rehash(sys.stdin.read().splitlines(), key)
    except leakscan.DenylistError as e:
        print(f"leakscan-rehash: {e}", file=sys.stderr)
        return 2
    sys.stdout.write(HEADER + "".join(d + "\n" for d in digests))
    print(f"leakscan-rehash: {len(digests)} digest(s). Set DENIED_COUNT in "
          f"tests/leakscan.py to {len(digests)}.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
