#!/usr/bin/env python3
"""scripts/release-manifests.py: the Homebrew formulas and the Scoop manifest
are a pure function of (version, repository, checksums.txt), pinned as whole
literal text on a fixture checksums file whose every hash is distinct; and an
asset missing from checksums.txt is refused, not written as an empty hash.

    python3 tests/release_manifests_test.py

`ruby -c` on the formulas runs in CI's release-dry-run job (a hosted runner
has ruby); this test needs nothing but python3.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "release-manifests.py"

ASSETS = [
    "muster_darwin_amd64.tar.gz", "muster_darwin_arm64.tar.gz",
    "muster_linux_amd64.tar.gz", "muster_linux_arm64.tar.gz",
    "muster-mirror_darwin_amd64.tar.gz", "muster-mirror_darwin_arm64.tar.gz",
    "muster-mirror_linux_amd64.tar.gz", "muster-mirror_linux_arm64.tar.gz",
    "muster_windows_amd64.zip", "muster_windows_arm64.zip",
]
# Every hash distinct and recognisable: hex digit i repeated 64 times would
# collide past 16 assets, so the index is spelled into the hash.
SUMS = {a: f"{i:02x}" * 32 for i, a in enumerate(ASSETS, start=1)}


def run(checksums: str, version: str = "1.2.3", repo: str = "Example/proj"):
    with tempfile.TemporaryDirectory() as t:
        cs = Path(t, "checksums.txt")
        cs.write_text(checksums)
        r = subprocess.run([sys.executable, str(SCRIPT), "--version", version, "--repo", repo,
                            "--checksums", str(cs), "--out", t], capture_output=True, text=True)
        files = {p.name: p.read_text() for p in Path(t).iterdir() if p.name != "checksums.txt"}
        return r, files


FULL = "".join(f"{SUMS[a]}  {a}\n" for a in ASSETS) + f"{'ff' * 32}  docker-compose.yml\n"
U = "https://github.com/Example/proj/releases/download/v1.2.3"

MUSTER_RB = textwrap.dedent(f"""\
    # Generated by scripts/release-manifests.py for muster 1.2.3; do not edit.
    class Muster < Formula
      desc "Command-line client for a muster server"
      homepage "https://github.com/Example/proj"
      version "1.2.3"
      license "MIT"

      on_macos do
        on_arm do
          url "{U}/muster_darwin_arm64.tar.gz"
          sha256 "{SUMS['muster_darwin_arm64.tar.gz']}"
        end
        on_intel do
          url "{U}/muster_darwin_amd64.tar.gz"
          sha256 "{SUMS['muster_darwin_amd64.tar.gz']}"
        end
      end

      on_linux do
        on_arm do
          url "{U}/muster_linux_arm64.tar.gz"
          sha256 "{SUMS['muster_linux_arm64.tar.gz']}"
        end
        on_intel do
          url "{U}/muster_linux_amd64.tar.gz"
          sha256 "{SUMS['muster_linux_amd64.tar.gz']}"
        end
      end

      def install
        bin.install "muster"
      end

      test do
        assert_match version.to_s, shell_output("#{{bin}}/muster --version")
      end
    end
    """)


class Manifests(unittest.TestCase):
    def test_writes_exactly_three_files(self):
        r, files = run(FULL)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(sorted(files), ["muster-mirror.rb", "muster.json", "muster.rb"])

    def test_cli_formula_literal(self):
        _, files = run(FULL)
        self.assertEqual(files["muster.rb"], MUSTER_RB)

    def test_mirror_formula_depends_on_tmux_and_names_mirror_archives(self):
        _, files = run(FULL)
        rb = files["muster-mirror.rb"]
        self.assertIn("class MusterMirror < Formula", rb)
        self.assertIn('  depends_on "tmux"\n', rb)
        for a in ASSETS:
            if a.startswith("muster-mirror_"):
                self.assertIn(f'      url "{U}/{a}"\n      sha256 "{SUMS[a]}"\n', rb)
            else:
                self.assertNotIn(SUMS[a], rb, f"the mirror formula carries {a}'s hash")
        self.assertIn('bin.install "muster-mirror"', rb)
        self.assertIn('shell_output("#{bin}/muster-mirror -version")', rb)

    def test_scoop_manifest(self):
        _, files = run(FULL)
        m = json.loads(files["muster.json"])
        self.assertEqual(m["version"], "1.2.3")
        self.assertEqual(m["bin"], "muster.exe")
        self.assertEqual(m["architecture"], {
            "64bit": {"url": f"{U}/muster_windows_amd64.zip", "hash": SUMS["muster_windows_amd64.zip"]},
            "arm64": {"url": f"{U}/muster_windows_arm64.zip", "hash": SUMS["muster_windows_arm64.zip"]},
        })
        self.assertEqual(m["autoupdate"]["hash"], {"url": "$baseurl/checksums.txt"})
        self.assertIn("tmux", m["description"], "the manifest says why there is no Windows muster-mirror")

    def test_leading_v_and_star_paths(self):
        # sha256sum -b writes "<hash> *<name>"
        r, files = run(FULL.replace("  muster_windows_amd64.zip", " *muster_windows_amd64.zip"), version="v1.2.3")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(json.loads(files["muster.json"])["architecture"]["64bit"]["hash"], SUMS["muster_windows_amd64.zip"])

    def test_missing_asset_refused(self):
        for a in ("muster_windows_arm64.zip", "muster-mirror_darwin_amd64.tar.gz", "muster_linux_arm64.tar.gz"):
            with self.subTest(asset=a):
                r, files = run("".join(l for l in FULL.splitlines(True) if not l.endswith(f"  {a}\n")))
                self.assertEqual(r.returncode, 2)
                self.assertIn(a, r.stderr)
                self.assertEqual(files, {}, "nothing is written when one asset is missing")

    def test_bad_arguments_refused(self):
        self.assertEqual(run(FULL, version="1.2")[0].returncode, 2)
        self.assertEqual(run(FULL, repo="not a repo")[0].returncode, 2)
        self.assertEqual(run("garbage line\n")[0].returncode, 2)


if __name__ == "__main__":
    unittest.main(verbosity=1)
